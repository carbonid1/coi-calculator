export type ResourceId = (typeof resourceIds)[number]

export interface Resource {
  id: ResourceId
  name: string
}

/** Readable labels for synthetic resources and unavailable game metadata. */
const fallbackResourceName = (id: ResourceId) => {
  const words = id.replace(/([a-z])([A-Z])/g, '$1 $2')
    .replace(/\b(?:iv|iii|ii|i)\b/gi, value => value.toUpperCase())
    .split(' ')
  const name = words.map(word => word.charAt(0).toUpperCase() + word.slice(1)).join(' ')

  return id.startsWith('steam') ? `Steam (${name.slice(6)})` : name
}

function createResources(): Record<ResourceId, Resource>
function createResources() {
  return Object.fromEntries(resourceIds.map(id => [id, { id, name: fallbackResourceName(id) }]))
}

export const resources = createResources()
